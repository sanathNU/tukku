tukku_rust_macro::kannada! {
    // Basic arithmetic example
    // ಸರಳ ಅಂಕಗಣಿತದ ಉದಾಹರಣೆ
    ಸಾರ್ವಜನಿಕ ಕಾರ್ಯ ಗುಣಾಕಾರ() {
        ಮಾಡು x = 5;
        ಮಾಡು y = 3;
        ಮಾಡು ಫಲಿತಾಂಶ = x * y;
        ಮುದ್ರಿಸು!("ಗುಣಾಕಾರ: {} * {} = {}", x, y, ಫಲಿತಾಂಶ);
    }

    // Loop example
    // ಲೂಪ್ ಉದಾಹರಣೆ
    ಸಾರ್ವಜನಿಕ ಕಾರ್ಯ ಲೂಪ್() {
        ಮಾಡು ಬದಲು ಮೊತ್ತ = 0;
        ಮಾಡು ಬದಲು i = 1;
        ಯಾವಾಗ i <= 5 {
            ಮೊತ್ತ = ಮೊತ್ತ + i;
            i = i + 1;
        }
        ಮುದ್ರಿಸು!("ಮೊತ್ತ: {}", ಮೊತ್ತ);
    }

    // Square example
    // ಕಾರ್ಯ ಉದಾಹರಣೆ
    ಸಾರ್ವಜನಿಕ ಕಾರ್ಯ ವರ್ಗ_ಫಲಿತಾಂಶ(ಸಂಖ್ಯೆ: i32) -> i32 {
        ಸಂಖ್ಯೆ * ಸಂಖ್ಯೆ
    }
}

fn main() {

    // Call the functions directly
    println!("ಗುಣಾಕಾರ ಉದಾಹರಣೆ:");
    ಗುಣಾಕಾರ();
    
    println!("\nಲೂಪ್ ಉದಾಹರಣೆ:");
    ಲೂಪ್();
    
    println!("\nವರ್ಗ ಉದಾಹರಣೆ:");
    let ಸಂಖ್ಯೆ = 4;
    println!("{} ನ ವರ್ಗ: {}", ಸಂಖ್ಯೆ, ವರ್ಗ_ಫಲಿತಾಂಶ(ಸಂಖ್ಯೆ));
}

